const DICT: Record<Locale, Dict> = { ru: RU, en: EN };

export function translate(
  key: string,
  locale: Locale,
  params?: Record<string, string | number>,
): string {
  let v = DICT[locale][key] ?? DICT.ru[key] ?? key;
  if (params) {
    for (const [k, val] of Object.entries(params)) {
      v = v.split(`{${k}}`).join(String(val));
    }
  }
  return v;
}

/**
 * Hook to get a translator bound to the current locale.
 * Re-renders when the locale changes.
 */
export function useT(): (key: string, params?: Record<string, string | number>) => string {
  const locale = useUIStore(s => s.locale);
  return (key, params) => translate(key, locale, params);
}

export function useLocale(): Locale {
  return useUIStore(s => s.locale);
}

/**
 * Default filename/folder-name used when creating a new node without a user-supplied name.
 * Reads the current locale synchronously so callers outside React (hotkeys, context menus)
 * can use it without a hook.
 */
export function defaultNodeName(kind: 'file' | 'dir'): string {
  const locale = useUIStore.getState().locale;
  if (kind === 'dir') return locale === 'en' ? 'new-folder' : 'новая-папка';
  return locale === 'en' ? 'new-file' : 'новый-файл';
}
